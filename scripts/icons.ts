// Regenerate contract/icons.ts from Octicons' 16px SVGs:
//   npm pack @primer/octicons@19.15.1 && tar xzf primer-octicons-*.tgz
//   npm run icons -- package/build/svg      (generates, then biome-formats)
// The set is the NAMES list below; add a name, re-run, commit the output.

import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const NAMES = [
  "alert",
  "arrow-left",
  "arrow-right",
  "bell",
  "calendar",
  "check",
  "check-circle",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevron-up",
  "circle",
  "clock",
  "code",
  "copy",
  "dash",
  "dot-fill",
  "download",
  "eye",
  "eye-closed",
  "file",
  "file-directory",
  "filter",
  "gear",
  "git-branch",
  "git-merge",
  "git-pull-request",
  "graph",
  "history",
  "home",
  "info",
  "issue-closed",
  "issue-opened",
  "kebab-horizontal",
  "link",
  "link-external",
  "lock",
  "moon",
  "pencil",
  "person",
  "play",
  "plus",
  "question",
  "search",
  "skip",
  "sort-desc",
  "star",
  "stop",
  "sun",
  "sync",
  "terminal",
  "three-bars",
  "trash",
  "triangle-down",
  "upload",
  "x",
  "x-circle",
] as const

const dir = process.argv[2]
if (!dir) throw new Error("usage: node scripts/icons.ts <octicons build/svg dir>")

const entries = NAMES.map((name) => {
  const svg = readFileSync(join(dir, `${name}-16.svg`), "utf8")
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
  if (paths.length === 0) throw new Error(`${name}: no paths`)
  return `  "${name}": [${paths.map((d) => JSON.stringify(d)).join(", ")}],`
})

writeFileSync(
  "contract/icons.ts",
  `// Generated by scripts/icons.ts from @primer/octicons 19.15.1 (16px). Do not edit.
// Octicons: MIT License, Copyright (c) GitHub Inc.

/** Path data per icon, drawn in a 0 0 16 16 box with fill="currentColor". */
export const ICONS = {
${entries.join("\n")}
} as const satisfies Record<string, readonly string[]>

export type IconName = keyof typeof ICONS
`
)
execFileSync("npx", ["biome", "format", "--write", "contract/icons.ts"], { stdio: "inherit" })
process.stdout.write(`contract/icons.ts: ${NAMES.length} icons\n`)
